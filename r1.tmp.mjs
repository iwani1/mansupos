import { chromium } from 'playwright-core';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
await page.locator('.product-card').first().waitFor(); await page.waitForTimeout(600);
await page.locator('.product-card').first().click();
await page.locator('.product-card').nth(1).click(); await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/variant.png` });
await page.locator('.variant-modal .button.primary').click(); await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/desktop.png` });
await page.getByRole('button', { name: /Prepare order GH/ }).click();
await page.getByRole('dialog', { name: 'Complete payment' }).waitFor(); await page.waitForTimeout(300);
await page.locator('.quick-cash button').nth(1).click(); await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/checkout.png` });
await page.keyboard.press('Escape');
const m = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await m.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
await m.locator('.product-card').first().waitFor(); await m.waitForTimeout(600);
await m.screenshot({ path: `${out}/phone.png` });
await browser.close();
